/// 4/8px-rhythm spacing scale, mirrored from the Stitch design system doc.
abstract final class AppSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 20; // screen margin
  static const double xxl = 24; // large card padding
  static const double sectionGap = 32;

  static const double screenMargin = xl;
  static const double cardPaddingSm = md;
  static const double cardPaddingMd = lg;
  static const double cardPaddingLg = xxl;
}
